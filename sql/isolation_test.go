package sql

import "testing"

func TestIsolationStatementParser(t *testing.T) {
	for _, q := range []string{"BEGIN ISOLATION LEVEL REPEATABLE READ", "BEGIN ISOLATION LEVEL READ COMMITTED READ WRITE", "START TRANSACTION WITH CONSISTENT SNAPSHOT", "SET SESSION TRANSACTION ISOLATION LEVEL REPEATABLE READ", "SET TRANSACTION ISOLATION LEVEL READ COMMITTED"} {
		if _, err := Parse(q); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
	}
	for _, q := range []string{"BEGIN ISOLATION LEVEL SERIALIZABLE", "BEGIN ISOLATION LEVEL READ UNCOMMITTED", "START TRANSACTION WITH CONSISTENT", "START TRANSACTION WITH CONSISTENT SNAPSHOT WITH CONSISTENT SNAPSHOT", "SET TRANSACTION ISOLATION LEVEL NONSENSE"} {
		if _, err := Parse(q); err == nil {
			t.Fatalf("accepted %s", q)
		}
	}
}
