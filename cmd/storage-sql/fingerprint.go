package main

import (
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"fmt"
	"hash"
	"math"
	"strings"

	"slopdb/db"
	"slopdb/sql"
)

type tableManifest struct {
	Name         string   `json:"name"`
	Columns      []string `json:"columns"`
	LogicalTypes []string `json:"logical_types"`
	OrderBy      []string `json:"order_by"`
	Rows         int64    `json:"rows"`
	LogicalBytes int64    `json:"logical_bytes"`
	EncodedBytes int64    `json:"encoded_bytes"`
	SHA256       string   `json:"sha256"`
}
type manifest struct {
	Version           int             `json:"version"`
	Format            string          `json:"format"`
	Dataset           string          `json:"dataset"`
	SQLSHA256         string          `json:"sql_sha256"`
	SQLBytes          int64           `json:"sql_bytes"`
	SchemaSQL         []string        `json:"schema_sql"`
	Tables            []tableManifest `json:"tables"`
	TotalRows         int64           `json:"total_rows"`
	TotalLogicalBytes int64           `json:"total_logical_bytes"`
}
type fingerprint struct {
	Name         string `json:"name"`
	Rows         int64  `json:"rows"`
	LogicalBytes int64  `json:"logical_bytes"`
	EncodedBytes int64  `json:"encoded_bytes"`
	SHA256       string `json:"sha256"`
}

func quote(name string) string { return `"` + strings.ReplaceAll(name, `"`, `""`) + `"` }
func quoted(names []string) string {
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = quote(n)
	}
	return strings.Join(q, ",")
}
func (m manifest) validate() error {
	if m.Version != 1 || m.Format != "slopdb-canonical-sql-v1" || m.Dataset == "" || len(m.Tables) == 0 || m.SQLBytes <= 0 {
		return fmt.Errorf("invalid canonical SQL manifest")
	}
	validHash := func(s string) bool { b, e := hex.DecodeString(s); return e == nil && len(b) == sha256.Size }
	if !validHash(m.SQLSHA256) {
		return fmt.Errorf("invalid SQL hash")
	}
	var rows, bytes int64
	names := map[string]bool{}
	for _, t := range m.Tables {
		if t.Name == "" || strings.ContainsRune(t.Name, 0) || names[t.Name] || len(t.Columns) == 0 || len(t.Columns) != len(t.LogicalTypes) || len(t.OrderBy) == 0 || t.Rows < 0 || t.LogicalBytes < 0 || t.EncodedBytes < 0 || !validHash(t.SHA256) {
			return fmt.Errorf("invalid table manifest %q", t.Name)
		}
		names[t.Name] = true
		cols := map[string]bool{}
		for i, c := range t.Columns {
			if c == "" || strings.ContainsRune(c, 0) || cols[c] {
				return fmt.Errorf("invalid column in %s", t.Name)
			}
			cols[c] = true
			switch t.LogicalTypes[i] {
			case "int64", "float64", "text":
			default:
				return fmt.Errorf("unsupported logical type %q", t.LogicalTypes[i])
			}
		}
		for _, c := range t.OrderBy {
			if !cols[c] {
				return fmt.Errorf("invalid order column in %s", t.Name)
			}
		}
		if t.Rows > math.MaxInt64-rows || t.LogicalBytes > math.MaxInt64-bytes {
			return fmt.Errorf("manifest totals overflow")
		}
		rows += t.Rows
		bytes += t.LogicalBytes
	}
	if rows != m.TotalRows || bytes != m.TotalLogicalBytes {
		return fmt.Errorf("manifest table totals disagree")
	}
	return nil
}

// Hash protocol v1 is independently generated by the canonical SQL dumper:
// R/u32 column count; NULL=0; int=1/i64; real=2/f64; text=3/u64/UTF-8.
// All numeric framing uses big endian. Signed zero hashes as positive zero.
func encodeRow(h hash.Hash, values []sql.Value, types []string) (logical, encoded int64, err error) {
	if len(values) != len(types) || uint64(len(values)) > math.MaxUint32 {
		return 0, 0, fmt.Errorf("fingerprint row width mismatch")
	}
	var b [9]byte
	b[0] = 'R'
	binary.BigEndian.PutUint32(b[1:5], uint32(len(values)))
	_, _ = h.Write(b[:5])
	encoded = 5
	for i, v := range values {
		if v.Null {
			b[0] = 0
			_, _ = h.Write(b[:1])
			encoded++
			continue
		}
		switch types[i] {
		case "int64":
			if v.Type != sql.ColInteger {
				return 0, 0, fmt.Errorf("column %d is not int64", i)
			}
			b[0] = 1
			binary.BigEndian.PutUint64(b[1:], uint64(v.Int))
			_, _ = h.Write(b[:])
			logical += 8
			encoded += 9
		case "float64":
			if v.Type != sql.ColReal || math.IsNaN(v.Real) || math.IsInf(v.Real, 0) {
				return 0, 0, fmt.Errorf("column %d is not finite float64", i)
			}
			f := v.Real
			if f == 0 {
				f = 0
			}
			b[0] = 2
			binary.BigEndian.PutUint64(b[1:], math.Float64bits(f))
			_, _ = h.Write(b[:])
			logical += 8
			encoded += 9
		case "text":
			if v.Type != sql.ColText {
				return 0, 0, fmt.Errorf("column %d is not text", i)
			}
			b[0] = 3
			binary.BigEndian.PutUint64(b[1:], uint64(len(v.Text)))
			_, _ = h.Write(b[:])
			_, _ = h.Write([]byte(v.Text))
			logical += int64(len(v.Text))
			encoded += 9 + int64(len(v.Text))
		default:
			return 0, 0, fmt.Errorf("unsupported logical type %q", types[i])
		}
	}
	return logical, encoded, nil
}
func verify(d *db.Database, m manifest) ([]fingerprint, error) {
	found := make([]fingerprint, 0, len(m.Tables))
	for _, t := range m.Tables {
		r, err := d.Query("SELECT " + quoted(t.Columns) + " FROM " + quote(t.Name) + " ORDER BY " + quoted(t.OrderBy))
		if err != nil {
			return nil, err
		}
		h := sha256.New()
		f := fingerprint{Name: t.Name}
		for r.Next() {
			values, e := r.Values()
			if e != nil {
				_ = r.Close()
				return nil, e
			}
			logical, encoded, e := encodeRow(h, values, t.LogicalTypes)
			if e != nil {
				_ = r.Close()
				return nil, fmt.Errorf("%s: %w", t.Name, e)
			}
			f.Rows++
			f.LogicalBytes += logical
			f.EncodedBytes += encoded
		}
		err = r.Err()
		_ = r.Close()
		if err != nil {
			return nil, err
		}
		f.SHA256 = hex.EncodeToString(h.Sum(nil))
		if f.Rows != t.Rows || f.LogicalBytes != t.LogicalBytes || f.EncodedBytes != t.EncodedBytes || f.SHA256 != t.SHA256 {
			return nil, fmt.Errorf("%s logical fingerprint mismatch: rows=%d logical_bytes=%d encoded_bytes=%d sha256=%s", t.Name, f.Rows, f.LogicalBytes, f.EncodedBytes, f.SHA256)
		}
		found = append(found, f)
		fmt.Printf("verified %s: %d rows %s\n", t.Name, f.Rows, f.SHA256)
	}
	return found, nil
}
